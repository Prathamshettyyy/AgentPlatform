from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, List, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


class RelevanceClassification(str, Enum):
    RELEVANT_FOR_FURTHER_EVALUATION = "RELEVANT_FOR_FURTHER_EVALUATION"
    POTENTIALLY_RELEVANT = "POTENTIALLY_RELEVANT"
    LIMITED_RELEVANCE = "LIMITED_RELEVANCE"
    INSUFFICIENT_INFORMATION = "INSUFFICIENT_INFORMATION"
    NOT_EVALUATED = "NOT_EVALUATED"


class ReviewStatus(str, Enum):
    PENDING_REVIEW = "PENDING_REVIEW"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    CHANGES_REQUESTED = "CHANGES_REQUESTED"


class AuthorityCategory(str, Enum):
    GOVERNMENT_AGENCY = "GOVERNMENT_AGENCY"
    STANDARDS_ORGANIZATION = "STANDARDS_ORGANIZATION"
    ACADEMIC_RESEARCH = "ACADEMIC_RESEARCH"
    INDUSTRY_TECHNICAL = "INDUSTRY_TECHNICAL"
    OTHER = "OTHER"


class ResearchQuery(BaseModel):
    """Targeted search query generated by the agent."""
    model_config = ConfigDict(extra="ignore")

    query_id: str
    foundation_type: str
    topic: str
    query_text: str
    target_source_types: List[str] = Field(default_factory=list)
    rationale: str = ""


class ResearchSource(BaseModel):
    """External technical source retrieved and verified by the research agent."""
    model_config = ConfigDict(extra="ignore")

    source_id: str
    title: str
    publisher: str
    url: str
    publication_date: Optional[str] = None
    last_updated: Optional[str] = None
    access_date: str = Field(default_factory=_now_iso)
    snippet: str
    topic: str
    authority_category: AuthorityCategory = AuthorityCategory.INDUSTRY_TECHNICAL
    claims_supported: List[str] = Field(default_factory=list)
    # Honest record of how far this source was actually checked.
    verification_status: str = "SEARCH_SNIPPET_ONLY"
    verification_note: str = (
        "Only the search-result snippet was available; full document text was not retrieved or verified."
    )


class ResearchFinding(BaseModel):
    """Specific technical finding extracted from one or more external sources."""
    model_config = ConfigDict(extra="ignore")

    finding_id: str
    foundation_type: str
    topic: str
    finding_text: str
    source_ids: List[str] = Field(default_factory=list)
    confidence_score: float = 0.85
    claim_origin: str = "EXTERNAL_RESEARCH"  # GEOTECH_CONSULTANT | EXTERNAL_RESEARCH | AI_COMPARISON | ENGINEER_CONFIRMATION_REQUIRED
    verification_status: str = "SOURCE_SUPPORTED"  # SOURCE_SUPPORTED | UNVERIFIED


class FoundationOption(BaseModel):
    """Comprehensive technical evaluation of an individual foundation technology."""
    model_config = ConfigDict(extra="ignore")

    name: str
    category: Literal["SHALLOW", "DEEP"]
    mentioned_in_geotech_report: bool = False
    description: str
    typical_applications: List[str] = Field(default_factory=list)
    soil_compatibility: str
    bearing_considerations: str
    settlement_considerations: str
    groundwater_considerations: str
    expansive_soil_considerations: str
    construction_methods: List[str] = Field(default_factory=list)
    equipment_requirements: List[str] = Field(default_factory=list)
    advantages: List[str] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    applicable_standards: List[str] = Field(default_factory=list)
    vendor_capabilities: List[str] = Field(default_factory=list)
    relevance_classification: RelevanceClassification = RelevanceClassification.NOT_EVALUATED
    relevance_reasoning: str = ""
    supporting_source_ids: List[str] = Field(default_factory=list)
    claim_basis: str = (
        "Geotechnical Consultant Recommendations vs. External Research Findings vs. "
        "AI-Generated Comparisons vs. Engineer-Confirmation Requirements are explicitly labeled per field."
    )


class FoundationComparison(BaseModel):
    """Structured matrix item comparing a foundation system against site criteria."""
    model_config = ConfigDict(extra="ignore")

    foundation_type: str
    category: Literal["SHALLOW", "DEEP"]
    typical_application: str
    soil_compatibility: str
    bearing_considerations: str
    settlement_considerations: str
    groundwater_considerations: str
    expansive_soil_considerations: str
    construction_complexity: str
    advantages: List[str] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    project_relevance: RelevanceClassification
    relevance_explanation: str
    missing_inputs: List[str] = Field(default_factory=list)


class ResearchGap(BaseModel):
    """Missing engineering information or data needed before design finalization."""
    model_config = ConfigDict(extra="ignore")

    gap_id: str
    category: str
    description: str
    impact: str
    required_action: str


class EngineerQuestion(BaseModel):
    """Specific question prepared for licensed design engineers."""
    model_config = ConfigDict(extra="ignore")

    question_id: str
    target_role: Literal["STRUCTURAL_ENGINEER", "GEOTECHNICAL_ENGINEER", "CIVIL_ENGINEER"]
    question: str
    context_reason: str


class HumanReviewRecord(BaseModel):
    """Audit entry documenting human engineering review."""
    model_config = ConfigDict(extra="ignore")

    reviewer: str
    decision: ReviewStatus
    reviewed_at: str = Field(default_factory=_now_iso)
    notes: Optional[str] = None


class FoundationResearchRequest(BaseModel):
    """Input payload to trigger a Foundation Research run."""
    project_id: str = "default"
    document_id: str
    analysis_report_id: Optional[str] = None
    foundation_types_to_research: Optional[List[str]] = None
    llm_profile: str = "foundation_research"
    search_provider: Optional[str] = None


class ReviewRequest(BaseModel):
    """Payload to update review status."""
    decision: ReviewStatus
    reviewed_by: str = "licensed_engineer"
    notes: Optional[str] = None


class FoundationResearchReport(BaseModel):
    """Complete, persistent Foundation Research Report."""
    model_config = ConfigDict(extra="ignore")

    report_id: str
    project_id: str
    document_id: str
    analysis_report_id: Optional[str] = None
    created_at: str = Field(default_factory=_now_iso)
    updated_at: str = Field(default_factory=_now_iso)
    llm_profile_used: str = "foundation_research"
    search_provider_used: str = "duckduckgo"

    # Human Review
    review_status: ReviewStatus = ReviewStatus.PENDING_REVIEW
    reviewed_by: Optional[str] = None
    reviewed_at: Optional[str] = None
    review_notes: Optional[str] = None
    review_history: List[HumanReviewRecord] = Field(default_factory=list)

    # Core Content
    geotechnical_summary: dict[str, Any] = Field(default_factory=dict)
    confirmed_documents_reviewed: List[str] = Field(default_factory=list)
    research_queries: List[ResearchQuery] = Field(default_factory=list)
    options_researched: List[FoundationOption] = Field(default_factory=list)
    comparisons: List[FoundationComparison] = Field(default_factory=list)
    external_sources: List[ResearchSource] = Field(default_factory=list)
    research_findings: List[ResearchFinding] = Field(default_factory=list)
    research_gaps: List[ResearchGap] = Field(default_factory=list)
    engineer_questions: List[EngineerQuestion] = Field(default_factory=list)
    markdown_content: str = ""

    disclaimer: str = (
        "PROFESSIONAL ENGINEERING DISCLAIMER: This research report compiles technical information "
        "from external engineering publications and relates them to the project's geotechnical investigation. "
        "It does NOT constitute a certified, stamped, or final foundation design. All findings, capacities, and "
        "suitability determinations must be independently verified and approved by a licensed Professional Engineer "
        "(PE / GE) or Structural Engineer (SE) prior to construction or procurement."
    )
